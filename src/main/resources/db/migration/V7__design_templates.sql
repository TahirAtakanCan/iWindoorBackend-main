CREATE TABLE IF NOT EXISTS design_templates (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id  bigint       NOT NULL REFERENCES companies (id),
    name        varchar(120) NOT NULL,
    category    varchar(32)  NOT NULL,
    design      jsonb        NOT NULL,
    sort_order  integer      NOT NULL DEFAULT 0,
    created_by  bigint       REFERENCES users (id),
    created_at  timestamptz  NOT NULL DEFAULT now(),
    updated_at  timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT design_templates_category_check
        CHECK (category IN ('WINDOW', 'DOOR', 'SLIDING', 'OTHER'))
);

CREATE UNIQUE INDEX IF NOT EXISTS uk_design_templates_company_name
    ON design_templates (company_id, lower(name));

CREATE INDEX IF NOT EXISTS ix_design_templates_company_category
    ON design_templates (company_id, category);
