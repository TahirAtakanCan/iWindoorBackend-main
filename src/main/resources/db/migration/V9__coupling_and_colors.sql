-- V9: Birleşik doğrama (COUPLING) ve renk/kaplama fiyat farkı.

-- 1) profiles.type CHECK: COUPLING
DO $$
DECLARE r record;
BEGIN
    FOR r IN
        SELECT con.conname
        FROM pg_constraint con
        JOIN pg_class rel ON rel.oid = con.conrelid
        WHERE con.contype = 'c'
          AND rel.relname = 'profiles'
          AND pg_get_constraintdef(con.oid) ILIKE '%type%FRAME%'
    LOOP
        EXECUTE format('ALTER TABLE profiles DROP CONSTRAINT %I', r.conname);
    END LOOP;
END $$;
ALTER TABLE profiles
    ADD CONSTRAINT profiles_type_check
        CHECK (type IN ('FRAME', 'SASH', 'MULLION', 'BEAD', 'ADAPTER', 'EXTENSION',
                        'DOOR_SASH', 'THRESHOLD', 'COUPLING'));

-- 2) Seri birleştirme ölçüleri
ALTER TABLE series
    ADD COLUMN IF NOT EXISTS coupling_face_mm double precision NOT NULL DEFAULT 20,
    ADD COLUMN IF NOT EXISTS coupling_gap_mm  double precision NOT NULL DEFAULT 0;

-- 3) Renk kataloğu
CREATE TABLE IF NOT EXISTS colors (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id      bigint REFERENCES companies (id),
    code            varchar(32)   NOT NULL,
    name            varchar(120)  NOT NULL,
    hex_outside     varchar(9)    NOT NULL,
    hex_inside      varchar(9)    NOT NULL,
    surcharge_pct   numeric(6, 2) NOT NULL DEFAULT 0,
    is_active       boolean       NOT NULL DEFAULT true,
    sort_order      integer       NOT NULL DEFAULT 0
);

CREATE UNIQUE INDEX IF NOT EXISTS ux_colors_company_code
    ON colors (coalesce(company_id, 0), code);

CREATE INDEX IF NOT EXISTS ix_colors_company ON colors (company_id);

-- 4) Mevcut şirket serilerine COUPLING profili
INSERT INTO profiles (code, name, type, width_mm, price_per_meter, currency, company_id, bar_length_mm,
                      is_default, is_active, series_id)
SELECT 'BRL-' || s.id, 'Birleştirme Profili', 'COUPLING', 20, 140, 'TRY', s.company_id, 6500, true, true, s.id
FROM series s
WHERE s.company_id IS NOT NULL
  AND NOT EXISTS (SELECT 1 FROM profiles p WHERE p.series_id = s.id AND p.type = 'COUPLING');

-- 5) Firma renkleri
INSERT INTO colors (company_id, code, name, hex_outside, hex_inside, surcharge_pct, is_active, sort_order)
SELECT c.id, v.code, v.name, v.hex_out, v.hex_in, v.pct, true, v.sort
FROM companies c
CROSS JOIN (VALUES
    ('white', 'Beyaz', '#F4F5F2', '#F4F5F2', 0::numeric, 10),
    ('CREAM', 'Krem', '#EFE6D2', '#EFE6D2', 10::numeric, 20),
    ('ANT-1', 'Antrasit (tek yüz)', '#3B3F45', '#F4F5F2', 25::numeric, 30),
    ('ANT-2', 'Antrasit (çift yüz)', '#3B3F45', '#3B3F45', 40::numeric, 40),
    ('OAK-1', 'Altın Meşe (tek yüz)', '#A8692F', '#F4F5F2', 30::numeric, 50),
    ('WAL-1', 'Ceviz (tek yüz)', '#5C3A21', '#F4F5F2', 30::numeric, 60)
) AS v(code, name, hex_out, hex_in, pct, sort)
WHERE NOT EXISTS (
    SELECT 1 FROM colors x WHERE x.company_id = c.id AND x.code = v.code
);
