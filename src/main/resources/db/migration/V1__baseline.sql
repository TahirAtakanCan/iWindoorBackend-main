CREATE TABLE companies (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    address     varchar(255),
    name        varchar(255),
    tax_number  varchar(255)
);

CREATE TABLE users (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email       varchar(255) NOT NULL,
    full_name   varchar(255),
    password    varchar(255) NOT NULL,
    role        varchar(255),
    company_id  bigint,
    CONSTRAINT users_role_check CHECK (role IN ('ADMIN', 'COMPANY_ADMIN', 'EMPLOYEE')),
    CONSTRAINT uk6dotkott2kjsp8vw4d0m25fb7 UNIQUE (email),
    CONSTRAINT fkin8gn4o1hpiwe6qe4ey7ykwq7 FOREIGN KEY (company_id) REFERENCES companies (id)
);

CREATE TABLE series (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    brand            varchar(255),
    name             varchar(255) NOT NULL,
    system_depth_mm  integer
);

CREATE TABLE profiles (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code              varchar(255) NOT NULL,
    currency          varchar(255),
    name              varchar(255) NOT NULL,
    price_per_meter   numeric(38, 2) NOT NULL,
    type              varchar(255) NOT NULL,
    weight_per_meter  double precision,
    width_mm          double precision,
    series_id         bigint NOT NULL,
    CONSTRAINT profiles_type_check CHECK (type IN ('FRAME', 'SASH', 'MULLION', 'BEAD', 'ADAPTER', 'EXTENSION')),
    CONSTRAINT uk4mn8xhcqvg8j0u78471o5h2f0 UNIQUE (code),
    CONSTRAINT fkqe7pq20xwu6gsvr9sftn761ad FOREIGN KEY (series_id) REFERENCES series (id)
);

CREATE TABLE glasses (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    currency      varchar(255),
    is_active     boolean,
    name          varchar(255) NOT NULL,
    price_per_m2  numeric(38, 2) NOT NULL,
    thickness_mm  integer
);

CREATE TABLE accessories (
    id        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code      varchar(255),
    currency  varchar(255),
    name      varchar(255) NOT NULL,
    price     numeric(38, 2) NOT NULL,
    unit      varchar(255) NOT NULL,
    CONSTRAINT accessories_unit_check CHECK (unit IN ('PIECE', 'METER', 'SET')),
    CONSTRAINT uk4v1hetc3q0ltc3lt0d0jqq7ci UNIQUE (code)
);

CREATE TABLE projects (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at   timestamp(6),
    currency     varchar(255),
    description  varchar(255),
    name         varchar(255) NOT NULL,
    total_price  numeric(38, 2),
    updated_at   timestamp(6),
    user_id      bigint,
    CONSTRAINT fkhswfwa3ga88vxv1pmboss6jhm FOREIGN KEY (user_id) REFERENCES users (id)
);

CREATE TABLE window_nodes (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    height        double precision,
    item_order    integer,
    node_type     varchar(255),
    stored_price  numeric(38, 2),
    width         double precision,
    glass_id      bigint,
    parent_id     bigint,
    profile_id    bigint,
    CONSTRAINT window_nodes_node_type_check CHECK (node_type IN ('FRAME', 'SASH', 'GLASS', 'MULLION_VERTICAL', 'MULLION_HORIZONTAL', 'EMPTY')),
    CONSTRAINT fkbcvb5tmhjc5vvb1m87tk4q5o5 FOREIGN KEY (glass_id) REFERENCES glasses (id),
    CONSTRAINT fkaee91s0ceuqkkkmiee5lrxmn5 FOREIGN KEY (parent_id) REFERENCES window_nodes (id),
    CONSTRAINT fk2193wogx3yxyam9uatngk1hhi FOREIGN KEY (profile_id) REFERENCES profiles (id)
);

CREATE TABLE window_units (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    height        double precision,
    name          varchar(255) NOT NULL,
    quantity      integer,
    unit_price    numeric(38, 2),
    width         double precision,
    project_id    bigint NOT NULL,
    root_node_id  bigint,
    CONSTRAINT ukkcjp21hdcmficroh88gxhhexl UNIQUE (root_node_id),
    CONSTRAINT fk4fceoebd8jeolk3r4nt8e5464 FOREIGN KEY (project_id) REFERENCES projects (id),
    CONSTRAINT fkj08n82d1giwmjr68bg5xr6sx6 FOREIGN KEY (root_node_id) REFERENCES window_nodes (id)
