-- V11: Satış fiyatı (fiyat modu, işçilik/montaj/kâr, m², override, ek kalemler).

ALTER TABLE companies
    ADD COLUMN IF NOT EXISTS pricing_mode          varchar(16)    NOT NULL DEFAULT 'COST_PLUS',
    ADD COLUMN IF NOT EXISTS profit_margin_pct     numeric(6, 2)  NOT NULL DEFAULT 30,
    ADD COLUMN IF NOT EXISTS labor_per_m2          numeric(12, 2) NOT NULL DEFAULT 400,
    ADD COLUMN IF NOT EXISTS install_per_m2        numeric(12, 2) NOT NULL DEFAULT 250,
    ADD COLUMN IF NOT EXISTS min_billable_area_m2  numeric(6, 2)  NOT NULL DEFAULT 1.00;

ALTER TABLE companies DROP CONSTRAINT IF EXISTS companies_pricing_mode_check;
ALTER TABLE companies
    ADD CONSTRAINT companies_pricing_mode_check CHECK (pricing_mode IN ('COST_PLUS', 'PER_M2'));

ALTER TABLE series
    ADD COLUMN IF NOT EXISTS sale_price_per_m2 numeric(12, 2);

ALTER TABLE window_units
    ADD COLUMN IF NOT EXISTS sale_price_override numeric(12, 2),
    ADD COLUMN IF NOT EXISTS sale_unit_price     numeric(12, 2);

ALTER TABLE projects
    ADD COLUMN IF NOT EXISTS sale_total numeric(14, 2);

CREATE TABLE IF NOT EXISTS project_extra_items (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id  bigint         NOT NULL REFERENCES projects (id) ON DELETE CASCADE,
    name        varchar(200)   NOT NULL,
    quantity    numeric(12, 3) NOT NULL DEFAULT 1,
    unit        varchar(16)    NOT NULL DEFAULT 'adet',
    unit_price  numeric(12, 2) NOT NULL,
    sort_order  integer        NOT NULL DEFAULT 0
);

CREATE INDEX IF NOT EXISTS ix_project_extra_items_project ON project_extra_items (project_id);
