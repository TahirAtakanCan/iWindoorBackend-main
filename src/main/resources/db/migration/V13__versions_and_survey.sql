-- V13: Teklif sürümleri ve keşif (saha ölçüsü) kayıtları.

CREATE TABLE IF NOT EXISTS quote_versions (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id    bigint         NOT NULL REFERENCES projects (id) ON DELETE CASCADE,
    version_no    integer        NOT NULL,
    label         varchar(200),
    snapshot      jsonb          NOT NULL,
    grand_total   numeric(14, 2) NOT NULL,
    sale_subtotal numeric(14, 2) NOT NULL,
    window_count  integer        NOT NULL,
    created_by    bigint REFERENCES users (id),
    created_at    timestamptz    NOT NULL DEFAULT now(),
    CONSTRAINT uq_quote_versions_project_no UNIQUE (project_id, version_no)
);

CREATE INDEX IF NOT EXISTS ix_quote_versions_project ON quote_versions (project_id);

ALTER TABLE projects
    ADD COLUMN IF NOT EXISTS approved_version_id bigint REFERENCES quote_versions (id) ON DELETE SET NULL;

ALTER TABLE companies
    ADD COLUMN IF NOT EXISTS survey_gap_mm numeric(5, 1) NOT NULL DEFAULT 10;

CREATE TABLE IF NOT EXISTS survey_items (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id      bigint         NOT NULL REFERENCES projects (id) ON DELETE CASCADE,
    room            varchar(120)   NOT NULL,
    product_type    varchar(16)    NOT NULL,
    hole_width      numeric(8, 1)  NOT NULL,
    hole_height     numeric(8, 1)  NOT NULL,
    quantity        integer        NOT NULL DEFAULT 1,
    note            varchar(1000),
    window_unit_id  bigint REFERENCES window_units (id) ON DELETE SET NULL,
    sort_order      integer        NOT NULL DEFAULT 0,
    created_at      timestamptz    NOT NULL DEFAULT now(),
    CONSTRAINT survey_items_product_type_check
        CHECK (product_type IN ('WINDOW', 'DOOR', 'BALCONY', 'SLIDING', 'OTHER'))
);

CREATE INDEX IF NOT EXISTS ix_survey_items_project ON survey_items (project_id);

CREATE TABLE IF NOT EXISTS survey_photos (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    survey_item_id  bigint       NOT NULL REFERENCES survey_items (id) ON DELETE CASCADE,
    content_type    varchar(64)  NOT NULL,
    data            bytea        NOT NULL,
    size_bytes      integer      NOT NULL,
    created_at      timestamptz  NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS ix_survey_photos_item ON survey_photos (survey_item_id);
