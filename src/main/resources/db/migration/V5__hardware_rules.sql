-- V5: Kanat donanımı kuralları (HARDWARE BOM → aksesuar kalemleri).

CREATE TABLE IF NOT EXISTS hardware_rules (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id      bigint REFERENCES companies (id),
    series_id       bigint REFERENCES series (id),
    kind            varchar(16)    NOT NULL,
    accessory_code  varchar(64)    NOT NULL,
    qty_type        varchar(24)    NOT NULL,
    qty             numeric(10, 3) NOT NULL DEFAULT 1,
    sort_order      integer        NOT NULL DEFAULT 0,
    CONSTRAINT hardware_rules_kind_check CHECK (kind IN ('TURN', 'TILT', 'TILT_TURN', 'SLIDE')),
    CONSTRAINT hardware_rules_qty_type_check CHECK (qty_type IN ('PER_SASH', 'PER_PERIMETER_METER'))
);

CREATE INDEX IF NOT EXISTS ix_hardware_rules_company_kind ON hardware_rules (company_id, kind);
