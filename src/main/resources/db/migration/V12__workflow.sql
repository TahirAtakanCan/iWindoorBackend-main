-- V12: İş takibi — müşteriler, proje durumları, tahsilat.

CREATE TABLE IF NOT EXISTS customers (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id  bigint       NOT NULL REFERENCES companies (id),
    name        varchar(200) NOT NULL,
    phone       varchar(50),
    email       varchar(200),
    address     varchar(500),
    tax_office  varchar(120),
    tax_number  varchar(50),
    note        varchar(2000),
    created_at  timestamptz  NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS ix_customers_company_name
    ON customers (company_id, lower(name));

ALTER TABLE projects
    ADD COLUMN IF NOT EXISTS customer_id       bigint REFERENCES customers (id),
    ADD COLUMN IF NOT EXISTS status            varchar(16) NOT NULL DEFAULT 'QUOTE',
    ADD COLUMN IF NOT EXISTS status_changed_at timestamptz,
    ADD COLUMN IF NOT EXISTS approved_at       timestamptz,
    ADD COLUMN IF NOT EXISTS approved_total    numeric(14, 2),
    ADD COLUMN IF NOT EXISTS delivery_date     date;

ALTER TABLE projects DROP CONSTRAINT IF EXISTS projects_status_check;
ALTER TABLE projects
    ADD CONSTRAINT projects_status_check
        CHECK (status IN ('QUOTE', 'APPROVED', 'PRODUCTION', 'INSTALLATION', 'DELIVERED', 'CANCELLED'));

CREATE TABLE IF NOT EXISTS project_status_history (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id  bigint       NOT NULL REFERENCES projects (id) ON DELETE CASCADE,
    from_status varchar(16),
    to_status   varchar(16)  NOT NULL,
    note        varchar(500),
    changed_by  bigint REFERENCES users (id),
    changed_at  timestamptz  NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS ix_project_status_history_project
    ON project_status_history (project_id);

CREATE TABLE IF NOT EXISTS payments (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id  bigint         NOT NULL REFERENCES projects (id) ON DELETE CASCADE,
    kind        varchar(8)     NOT NULL DEFAULT 'PAYMENT',
    amount      numeric(14, 2) NOT NULL,
    paid_at     date           NOT NULL,
    method      varchar(16)    NOT NULL,
    note        varchar(500),
    created_by  bigint REFERENCES users (id),
    created_at  timestamptz    NOT NULL DEFAULT now(),
    CONSTRAINT payments_kind_check CHECK (kind IN ('PAYMENT', 'REFUND')),
    CONSTRAINT payments_amount_check CHECK (amount > 0),
    CONSTRAINT payments_method_check CHECK (method IN ('CASH', 'CARD', 'TRANSFER', 'CHECK', 'OTHER'))
);

CREATE INDEX IF NOT EXISTS ix_payments_project ON payments (project_id);

-- Tek seferlik doldurma: customer_name dolu, customer_id boş → müşteri eşleştir/oluştur.
DO $$
DECLARE
    r RECORD;
    cid bigint;
BEGIN
    FOR r IN
        SELECT p.id AS project_id,
               u.company_id AS company_id,
               trim(p.customer_name) AS cname,
               NULLIF(trim(p.customer_phone), '') AS cphone,
               NULLIF(trim(p.customer_email), '') AS cemail,
               NULLIF(trim(p.customer_address), '') AS caddress
        FROM projects p
                 JOIN users u ON u.id = p.user_id
        WHERE p.customer_id IS NULL
          AND p.customer_name IS NOT NULL
          AND trim(p.customer_name) <> ''
        LOOP
            SELECT c.id
            INTO cid
            FROM customers c
            WHERE c.company_id = r.company_id
              AND lower(c.name) = lower(r.cname)
              AND COALESCE(c.phone, '') = COALESCE(r.cphone, '')
            LIMIT 1;

            IF cid IS NULL THEN
                INSERT INTO customers (company_id, name, phone, email, address)
                VALUES (r.company_id, r.cname, r.cphone, r.cemail, r.caddress)
                RETURNING id INTO cid;
            END IF;

            UPDATE projects SET customer_id = cid WHERE id = r.project_id;
        END LOOP;
END $$;
